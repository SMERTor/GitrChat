-- GitrChat private-two-person feature migration.
-- Review and apply in Supabase SQL Editor after backing up the project.

alter table public.messages
  add column if not exists reply_to_message_id bigint
    references public.messages(id) on delete set null,
  add column if not exists reply_to_text text,
  add column if not exists reply_to_user_name text;

create table if not exists public.message_reactions (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 16),
  created_at timestamptz not null default now(),
  unique(message_id, user_id, emoji)
);

alter table public.message_reactions enable row level security;
grant select, insert, delete on public.message_reactions to authenticated;
grant usage, select on sequence public.message_reactions_id_seq to authenticated;

drop policy if exists "Chat users can read reactions" on public.message_reactions;
create policy "Chat users can read reactions"
  on public.message_reactions for select to authenticated using (true);

drop policy if exists "Users add own reactions" on public.message_reactions;
create policy "Users add own reactions"
  on public.message_reactions for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users remove own reactions" on public.message_reactions;
create policy "Users remove own reactions"
  on public.message_reactions for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Audio files use the existing private chat-media bucket.
update storage.buckets
set allowed_mime_types = array[
  'image/jpeg','image/png','image/webp','image/heic',
  'video/mp4','video/quicktime','audio/mp4','audio/aac',
  'audio/m4a','audio/mpeg','audio/ogg','audio/wav'
]
where id = 'chat-media';

alter table public.messages drop constraint if exists messages_body_or_media_check;
alter table public.messages add constraint messages_body_or_media_check check (
  (body is not null and char_length(trim(body)) between 1 and 2000
    and media_path is null and media_type is null)
  or
  (body is null and media_path is not null
    and media_type in ('image','video_circle','voice'))
);
