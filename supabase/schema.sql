-- OneChat base schema. Existing production project already has profiles/messages.
-- For a fresh project, run the base schema first, then the media migration below.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 24),
  updated_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text,
  created_at timestamptz not null default now(),
  media_path text,
  media_type text,
  media_duration_seconds integer,
  constraint messages_body_or_media_check check (
    (body is not null and char_length(trim(body)) between 1 and 2000 and media_path is null and media_type is null)
    or (body is null and media_path is not null and media_type in ('image','video_circle'))
  ),
  constraint messages_media_duration_check check (
    media_duration_seconds is null or media_duration_seconds between 1 and 60
  )
);

create index if not exists messages_created_at_idx on public.messages(created_at desc);
create index if not exists messages_user_id_idx on public.messages(user_id);
alter table public.profiles enable row level security;
alter table public.messages enable row level security;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, delete on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- Policies are intentionally scoped to authenticated sessions. The app uses Supabase
-- anonymous sign-in, which still receives the authenticated Postgres role.
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='Profiles are readable by authenticated users') then
    create policy "Profiles are readable by authenticated users" on public.profiles for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='Users can create their own profile') then
    create policy "Users can create their own profile" on public.profiles for insert to authenticated with check ((select auth.uid()) = id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='Users can update their own profile') then
    create policy "Users can update their own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='messages' and policyname='Authenticated users can read messages') then
    create policy "Authenticated users can read messages" on public.messages for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='messages' and policyname='Users can send messages as themselves') then
    create policy "Users can send messages as themselves" on public.messages for insert to authenticated with check ((select auth.uid()) = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='messages' and policyname='Users can delete their own messages') then
    create policy "Users can delete their own messages" on public.messages for delete to authenticated using ((select auth.uid()) = user_id);
  end if;
end $$;

-- Media storage: private bucket, users may upload/delete only within their own UUID folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-media','chat-media',false,52428800,
  array['image/jpeg','image/png','image/webp','image/heic','video/mp4','video/quicktime'])
on conflict (id) do update set public=false, file_size_limit=52428800,
  allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists "Chat media readable by chat users" on storage.objects;
create policy "Chat media readable by chat users" on storage.objects
  for select to authenticated using (bucket_id='chat-media');
drop policy if exists "Users upload media to own folder" on storage.objects;
create policy "Users upload media to own folder" on storage.objects
  for insert to authenticated with check (
    bucket_id='chat-media' and (storage.foldername(name))[1]=(select auth.uid())::text
  );
drop policy if exists "Users delete media from own folder" on storage.objects;
create policy "Users delete media from own folder" on storage.objects
  for delete to authenticated using (
    bucket_id='chat-media' and (storage.foldername(name))[1]=(select auth.uid())::text
  );

-- Realtime publication registration is idempotent.
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='messages') then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
